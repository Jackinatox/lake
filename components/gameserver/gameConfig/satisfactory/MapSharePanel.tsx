'use client';

import {
    getMapShareLink,
    regenerateMapShareLink,
    setMapShareLinkEnabled,
    type MapShareLinkInfo,
    type MapShareLinkResult,
} from '@/app/actions/gameservers/satisfactoryMap';
import {
    AlertDialog,
    AlertDialogAction,
    AlertDialogCancel,
    AlertDialogContent,
    AlertDialogDescription,
    AlertDialogFooter,
    AlertDialogHeader,
    AlertDialogTitle,
    AlertDialogTrigger,
} from '@/components/ui/alert-dialog';
import { Button } from '@/components/ui/button';
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from '@/components/ui/card';
import { Input } from '@/components/ui/input';
import { Label } from '@/components/ui/label';
import { Skeleton } from '@/components/ui/skeleton';
import { Switch } from '@/components/ui/switch';
import { useToast } from '@/hooks/use-toast';
import { Check, Copy, Loader2, RefreshCw, Share2 } from 'lucide-react';
import { useFormatter, useNow, useTranslations } from 'next-intl';
import { useEffect, useState } from 'react';
import type { GameConfigPanelProps } from '../types';

type ShareState =
    | { status: 'loading' }
    | { status: 'ready'; link: MapShareLinkInfo | null }
    | { status: 'error' };

/**
 * The server's share link for the interactive map: one per server, no expiry, toggled and
 * regenerated by the owner. Players open it without an account and always get the newest save.
 * See docs/satisfactory-interactive-map.md.
 */
export default function MapSharePanel({ server }: GameConfigPanelProps) {
    const t = useTranslations('gameserver.config.satisfactory.share');
    const format = useFormatter();
    const now = useNow({ updateInterval: 60_000 });
    const { toast } = useToast();
    const [state, setState] = useState<ShareState>({ status: 'loading' });
    const [busy, setBusy] = useState(false);
    const [copied, setCopied] = useState(false);

    useEffect(() => {
        let cancelled = false;
        getMapShareLink(server.identifier).then(
            (result) => {
                if (cancelled) return;
                setState(
                    result.status === 'ok'
                        ? { status: 'ready', link: result.link }
                        : { status: 'error' },
                );
            },
            () => {
                if (!cancelled) setState({ status: 'error' });
            },
        );
        return () => {
            cancelled = true;
        };
    }, [server.identifier]);

    const run = async (action: () => Promise<MapShareLinkResult>) => {
        setBusy(true);
        try {
            const result = await action();
            if (result.status !== 'ok') throw new Error('Share link action failed');
            setState({ status: 'ready', link: result.link });
            setCopied(false);
        } catch {
            toast({
                title: t('actionFailedTitle'),
                description: t('actionFailedDescription'),
                variant: 'destructive',
            });
        } finally {
            setBusy(false);
        }
    };

    const handleCopy = async (url: string) => {
        try {
            await navigator.clipboard.writeText(url);
            setCopied(true);
            setTimeout(() => setCopied(false), 2000);
        } catch {
            toast({ title: t('copyFailed'), variant: 'destructive' });
        }
    };

    const link = state.status === 'ready' ? state.link : null;
    const enabled = link?.enabled ?? false;

    return (
        <Card>
            <CardHeader className="space-y-1.5">
                <CardTitle className="flex items-center gap-2 text-base">
                    <Share2 className="h-4 w-4" />
                    {t('title')}
                </CardTitle>
                <CardDescription>{t('description')}</CardDescription>
            </CardHeader>
            <CardContent className="space-y-4">
                {state.status === 'loading' ? (
                    <Skeleton className="h-10 w-full" />
                ) : state.status === 'error' ? (
                    <p className="rounded-md border border-dashed py-4 text-center text-sm text-muted-foreground">
                        {t('loadFailed')}
                    </p>
                ) : (
                    <>
                        <div className="flex items-center justify-between gap-3">
                            <Label htmlFor="map-share-enabled" className="text-sm font-medium">
                                {t('enabledLabel')}
                            </Label>
                            <Switch
                                id="map-share-enabled"
                                checked={enabled}
                                disabled={busy}
                                onCheckedChange={(checked) =>
                                    void run(() =>
                                        setMapShareLinkEnabled(server.identifier, checked),
                                    )
                                }
                            />
                        </div>

                        {link && enabled && (
                            <div className="space-y-2">
                                <div className="flex gap-2">
                                    <Input
                                        readOnly
                                        value={link.url}
                                        aria-label={t('linkLabel')}
                                        className="font-mono text-xs"
                                        onFocus={(event) => event.currentTarget.select()}
                                    />
                                    <Button
                                        variant="outline"
                                        className="shrink-0"
                                        onClick={() => void handleCopy(link.url)}
                                    >
                                        {copied ? (
                                            <Check className="h-4 w-4" />
                                        ) : (
                                            <Copy className="h-4 w-4" />
                                        )}
                                        {copied ? t('copied') : t('copy')}
                                    </Button>
                                </div>
                                <p className="text-xs text-muted-foreground">
                                    {link.lastUsedAt
                                        ? t('lastUsed', {
                                              time: format.relativeTime(
                                                  new Date(link.lastUsedAt),
                                                  now,
                                              ),
                                          })
                                        : t('neverUsed')}
                                </p>
                            </div>
                        )}

                        {link && (
                            <AlertDialog>
                                <AlertDialogTrigger asChild>
                                    <Button variant="outline" size="sm" disabled={busy}>
                                        {busy ? (
                                            <Loader2 className="h-4 w-4 animate-spin" />
                                        ) : (
                                            <RefreshCw className="h-4 w-4" />
                                        )}
                                        {t('regenerate')}
                                    </Button>
                                </AlertDialogTrigger>
                                <AlertDialogContent>
                                    <AlertDialogHeader>
                                        <AlertDialogTitle>{t('regenerateTitle')}</AlertDialogTitle>
                                        <AlertDialogDescription>
                                            {t('regenerateDescription')}
                                        </AlertDialogDescription>
                                    </AlertDialogHeader>
                                    <AlertDialogFooter>
                                        <AlertDialogCancel>{t('cancel')}</AlertDialogCancel>
                                        <AlertDialogAction
                                            onClick={() =>
                                                void run(() =>
                                                    regenerateMapShareLink(server.identifier),
                                                )
                                            }
                                        >
                                            {t('regenerateConfirm')}
                                        </AlertDialogAction>
                                    </AlertDialogFooter>
                                </AlertDialogContent>
                            </AlertDialog>
                        )}
                    </>
                )}

                <p className="text-xs text-muted-foreground">{t('warning')}</p>
            </CardContent>
        </Card>
    );
}
